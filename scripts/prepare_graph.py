"""Load J/h .npy files and generate a header for the original CUDA benchmark."""
import argparse
import json
from pathlib import Path
import numpy as np


def prepare_graph(j_path, h_path, output, binary_data=False):
    J = np.load(j_path, allow_pickle=False)
    n = J.shape[0]
    h = np.load(h_path, allow_pickle=False) if h_path else np.zeros(n)
    j32 = np.ascontiguousarray(J, dtype=np.float32)
    h32 = np.ascontiguousarray(h, dtype=np.float32)

    def literal(value):
        text = format(float(value), ".9g")
        if "." not in text and "e" not in text:
            text += ".0"
        return text + "f"

    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    if binary_data:
        # Keep large matrices out of the C++ compiler; preserve the header interface.
        data_path = output.with_suffix(".bin").resolve()
        with data_path.open("wb") as data:
            j32.tofile(data)
            h32.tofile(data)
        output.write_text(
            f"const int n_pbits = {n};\n"
            "std::vector<float> graph_J(n_pbits * n_pbits), graph_h(n_pbits);\n"
            "std::vector<int> graph_m(n_pbits, -1);\n"
            "float *h_J = graph_J.data(), *h_h = graph_h.data();\n"
            "int *h_m = graph_m.data();\n"
            f"FILE* graph_file = fopen({json.dumps(str(data_path))}, \"rb\");\n"
            "fread(h_J, sizeof(float), graph_J.size(), graph_file);\n"
            "fread(h_h, sizeof(float), graph_h.size(), graph_file);\n"
            "fclose(graph_file);\n"
        )
        return n
    with output.open("w") as f:
        f.write("// Generated by scripts/prepare_graph.py; float32, row-major.\n")
        f.write(f"const int n_pbits = {n};\n")
        # Static storage avoids placing multi-megabyte arrays on the CPU stack.
        f.write(f"static float h_J[{n * n}] = {{\n")
        for row in j32:
            f.write("    " + ", ".join(map(literal, row)) + ",\n")
        f.write("};\n")
        f.write(f"static float h_h[{n}] = {{" + ", ".join(map(literal, h32)) + "};\n")
        f.write(f"static int h_m[{n}] = {{" + ", ".join(["-1"] * n) + "};\n")
    return n


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--J", required=True, type=Path)
    parser.add_argument("--h", type=Path, help="Bias vector; omitted means all zeros")
    parser.add_argument(
        "--binary-data", action="store_true",
        help="Generate a small header loading a float32 binary sidecar",
    )
    parser.add_argument("--output", default="executable/graph_data.h", type=Path)
    args = parser.parse_args()
    n = prepare_graph(args.J, args.h, args.output, args.binary_data)
    print(f"Wrote {args.output}: n={n}, float32, initial spins=-1")
