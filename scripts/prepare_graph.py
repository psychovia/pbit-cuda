"""Load J/h .npy files and generate a header for the original CUDA benchmark."""
import argparse
from pathlib import Path
import numpy as np


def prepare_graph(j_path, h_path, output):
    J = np.load(j_path, allow_pickle=False)
    h = np.load(h_path, allow_pickle=False)
    if J.ndim != 2 or J.shape[0] == 0 or J.shape[0] != J.shape[1]:
        raise ValueError("J must have shape (n,n), n > 0")
    n = J.shape[0]
    if h.shape != (n,):
        raise ValueError("h must have shape (n,)")
    for name, array in (("J", J), ("h", h)):
        if array.dtype.kind != "f" or not np.isfinite(array).all():
            raise ValueError(f"{name} must contain finite floating-point values")
    with np.errstate(over="ignore", under="ignore"):
        j32 = np.ascontiguousarray(J, dtype=np.float32)
        h32 = np.ascontiguousarray(h, dtype=np.float32)
    for original, converted in ((J, j32), (h, h32)):
        if not np.isfinite(converted).all() or np.any((original != 0) & (converted == 0)):
            raise ValueError("Values overflow or underflow float32")
    if np.any(np.diag(j32) != 0) or not np.array_equal(j32, j32.T):
        raise ValueError("J must be symmetric with zero diagonal after float32 conversion")

    def literal(value):
        text = format(float(value), ".9g")
        if "." not in text and "e" not in text:
            text += ".0"
        return text + "f"

    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w") as f:
        f.write("// Generated by scripts/prepare_graph.py; float32, row-major.\n")
        f.write(f"const int n_pbits = {n};\n")
        # Static storage avoids placing multi-megabyte arrays on the CPU stack.
        f.write(f"static float h_J[{n*n}] = {{\n")
        for row in j32:
            f.write("    " + ", ".join(map(literal, row)) + ",\n")
        f.write("};\n")
        f.write(f"static float h_h[{n}] = {{" + ", ".join(map(literal, h32)) + "};\n")
        f.write(f"static int h_m[{n}] = {{" + ", ".join(["-1"] * n) + "};\n")
    return n


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--J", required=True, type=Path)
    parser.add_argument("--h", required=True, type=Path)
    parser.add_argument("--output", default="executable/graph_data.h", type=Path)
    args = parser.parse_args()
    n = prepare_graph(args.J, args.h, args.output)
    print(f"Wrote {args.output}: n={n}, float32, initial spins=-1")
